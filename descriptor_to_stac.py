#!/usr/bin/env python3
"""Merge CLMS data descriptors into CDSE STAC collection JSONs.

Reads the per-dataset data descriptors
(datasets/<name>/data_descriptor/<name>.json, schema 0.0.4) and the CLMS
collections of the CDSE STAC catalogue (https://stac.dataspace.copernicus.eu/v1,
the catalogue behind https://browser.stac.dataspace.copernicus.eu/), and writes
one enriched collection JSON per dataset to datasets/<name>/stac/collection/.

NetCDF is the official format of the CLMS datasets; the COG is created from it.
A dataset is therefore described from its NetCDF collection
(clms_<name>_nc -> collection-clms_<name>_nc.json). The COG collection
(clms_<name>_cog) is used only for a dataset the catalogue serves in COG only.

In a NetCDF collection the layers are the bands of the single "Product" asset,
so the layer fields of the descriptor are added to those bands. In a COG
collection every layer is an item asset of its own.

The merge is strictly add-only: existing STAC values are never modified or
removed. Descriptor fields with no STAC equivalent are added as custom
"cdse:*" (Browser display text) or "clms:*" (display order/flag, frequency,
spatial coverage label) fields, documented in docs/stac/stac_custom_fields.md.
Conflicts and unmatched entities are written to stac_merge_report.md.

The links the catalogue API generates (self, root, parent, items, queryables)
are dropped, and keys are written in the order of the template in
templates/stac/collection/.

Usage:
    python descriptor_to_stac.py            # download from the live catalogue
    python descriptor_to_stac.py <folder>   # read collection-*.json from a folder
"""

import copy
import datetime
import json
import re
import sys
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent
DATASETS_DIR = REPO_ROOT / "datasets"
REPORT_PATH = REPO_ROOT / "stac_merge_report.md"
TEMPLATE_DIR = REPO_ROOT / "templates" / "stac" / "collection"
# format suffix of the collection id -> template
TEMPLATE_PATHS = {
    "nc": TEMPLATE_DIR / "stac_collection_template.json",
    "cog": TEMPLATE_DIR / "stac_collection_template_cog.json",
}
# the format a dataset is described from, in order of preference
FORMATS = ("nc", "cog")

# Descriptor layer names follow the COG file names; some NetCDF variables are
# named differently. Layer name, whole or without its leading segment(s) (lower
# case, '-' -> '_') -> NetCDF variable name(s); the first one the collection has
# is used. An empty list means the layer has no single NetCDF variable.
NETCDF_ALIASES = {
    "lswt_lswt": ["lake_surface_water_temperature"],
    "rw": [],  # water-leaving reflectance: one variable per wavelength (rw<nnn>_rep)
    "dob": ["day_of_burn"],
    "cp": ["classification_probability"],
    "bf": ["burned_fraction"],
    "lfp": ["large_fraction_probability"],
    "lbefore": ["length_before"],
    "lafter": ["length_after"],
    "fobs": ["frac_valid_obs"],
    "tmean": ["turbidity_mean", "turbidity_blended_mean"],
    "tsi": ["trophic_state_index", "trophic_state_mean"],
    "fcbprob": ["floating_cyanobacteria"],
    "max_lts": ["max"],
    "mean_lts": ["mean"],
    "median_lts": ["median"],
    "min_lts": ["min"],
    "stdev_lts": ["stdev"],
    "ci": ["correlation_swi_gldas"],
}

CATALOGUE_URL = "https://stac.dataspace.copernicus.eu/v1"
# links generated by the catalogue API; they are not part of the collection source
API_LINK_RELS = {
    "self",
    "root",
    "parent",
    "items",
    "http://www.opengis.net/def/rel/ogc/1.0/queryables",
}

RASTER_EXT = "https://stac-extensions.github.io/raster/v2.0.0/schema.json"

MEDIA_TYPES = {
    ".sld": "application/vnd.ogc.sld+xml",
    ".txt": "text/plain",
    ".qml": "application/xml",
    ".clr": "text/plain",
    ".png": "image/png",
    ".jpg": "image/jpeg",
}


def norm_layer_name(file_name):
    return file_name.strip().lower().replace("-", "_")


def parse_resolution_m(text):
    """'300m' -> 300, '1km' -> 1000, '12.5km' -> 12500, 'vector'/'' -> None."""
    m = re.fullmatch(r"([\d.]+)\s*(m|km)", text.strip().lower())
    if not m:
        return None
    value = float(m.group(1))
    return value * 1000 if m.group(2) == "km" else value


def to_number(text):
    try:
        value = float(text)
    except (TypeError, ValueError):
        return None
    return int(value) if value == int(value) else value


class CollectionLog:
    """Per-collection merge log: additions, conflicts, informational notes."""

    def __init__(self, name, fmt="cog"):
        self.name = name
        self.format = fmt
        self.added = []
        self.conflicts = []
        self.notes = []
        self.unmatched_layers = []
        self.assets_without_layer = []
        self.matched = {}


def match_layer_to_asset(file_name, item_assets):
    """Match a descriptor layer fileName to one or more item_assets keys.

    The catalogue keys do not carry the product prefix of the fileName
    (NDVI300-NDVI -> ndvi, LST10-DC-MIN -> dc_min_00_11 + dc_min_12_23), so the
    rules of match_name() are tried on the full name first and then with the
    leading segments removed one by one.
    """
    segments = re.split(r"[-_]", file_name.strip())
    for start in range(len(segments)):
        keys = match_name("-".join(segments[start:]), item_assets)
        if keys:
            return keys
    return []


def match_layer_to_band(file_name, bands):
    """Match a descriptor layer fileName to the name(s) of NetCDF variables.

    The NETCDF_ALIASES table is tried first; a layer it does not settle goes
    through the same rules as for item assets, applied to the band names.
    """
    by_name = {band["name"]: {"bands": [band]} for band in bands}
    segments = re.split(r"[-_]", file_name.strip().lower())
    for start in range(len(segments)):
        tail = "_".join(segments[start:])
        if tail not in NETCDF_ALIASES:
            continue
        if not NETCDF_ALIASES[tail]:
            return []
        for name in NETCDF_ALIASES[tail]:
            if name in by_name:
                return [name]
    return match_layer_to_asset(file_name, by_name)


def match_name(file_name, item_assets):
    """Match one candidate name to item_assets keys.

    1. exact match on lowercase with '-' -> '_'
    2. keys extending the normalized name with an '_suffix' (may be several,
       e.g. LST10-DC-MIN -> lst10_dc_min_00_11 + lst10_dc_min_12_23)
    3. unique key ending in '_<normalized name>'
    4. unique key equal to / ending in the compact form (underscores stripped,
       e.g. SWI_001 -> swi1km_swi001)
    5. unique asset whose band name equals the last fileName segment
       (e.g. LAI1KM-LAI -> lai_lai, LIE-GLOBAL-P -> lie500_p)
    6. unique key starting with the compact form (e.g. SCE -> sce500)
    """
    norm = norm_layer_name(file_name)
    compact = norm.replace("_", "")
    lowered = {key.lower(): key for key in item_assets}
    if norm in lowered:
        return [lowered[norm]]
    prefixed = [key for low, key in lowered.items() if low.startswith(norm + "_")]
    if prefixed:
        return sorted(prefixed)
    for candidates in (
        [key for low, key in lowered.items() if low.endswith("_" + norm)],
        [key for low, key in lowered.items() if low.replace("_", "") == compact],
        [key for low, key in lowered.items() if low.replace("_", "").endswith(compact)],
        [
            key
            for key, asset in item_assets.items()
            if any(
                (band.get("name") or "").lower().replace("_", "")
                == re.split(r"[-_]", file_name)[-1].lower()
                for band in asset.get("bands", [])
            )
        ],
        [key for low, key in lowered.items() if len(compact) >= 3 and low.replace("_", "").startswith(compact)],
    ):
        if len(candidates) == 1:
            return candidates
    return []


def add_field(target, key, value, log, where):
    """Add-only setter: never overwrites, logs a conflict on differing values."""
    if key in target:
        if target[key] != value:
            log.conflicts.append(
                f"`{where}.{key}` already `{target[key]!r}`, descriptor has `{value!r}` (kept existing)"
            )
        return
    target[key] = value
    log.added.append(f"`{where}.{key}`")


def merge_collection_level(coll, desc, log):
    add_field(coll, "cdse:browser_name", desc["browserName"], log, "collection")
    add_field(coll, "cdse:browser_search_path", desc["browserSearchPath"], log, "collection")

    if desc["collectionDescription"].strip() != coll.get("description", "").strip():
        add_field(coll, "cdse:collection_description", desc["collectionDescription"], log, "collection")
        log.notes.append("descriptor `collectionDescription` differs from STAC `description`")

    if desc.get("spatialCoverage"):
        add_field(coll, "clms:spatial_coverage", desc["spatialCoverage"], log, "collection")
    if desc.get("frequency"):
        add_field(coll, "clms:frequency", desc["frequency"], log, "collection")

    link = desc.get("linkToCLMS", "").strip()
    if link:
        about_hrefs = {
            l.get("href", "").rstrip("/") for l in coll.get("links", []) if l.get("rel") == "about"
        }
        if link.rstrip("/") not in about_hrefs:
            coll.setdefault("links", []).append(
                {"rel": "about", "href": link, "type": "text/html", "title": "CLMS product page"}
            )
            log.added.append("`links[]` rel=about (CLMS product page)")
            if about_hrefs:
                log.conflicts.append(
                    f"`linkToCLMS` `{link}` differs from existing about link(s) {sorted(about_hrefs)}"
                )

    # comparison-only fields: log, never write
    start = desc.get("temporalExtent", {}).get("start", "")
    interval = coll.get("extent", {}).get("temporal", {}).get("interval", [[None, None]])[0]
    if start and interval[0] and not str(interval[0]).startswith(str(start)):
        log.notes.append(
            f"descriptor temporalExtent.start `{start}` vs STAC interval start `{interval[0]}`"
        )

    res_m = parse_resolution_m(desc.get("nominalSpatialResolution", ""))
    gsd = coll.get("summaries", {}).get("gsd", [])
    if res_m is not None and gsd and abs(gsd[0] - res_m) > 0.5:
        log.notes.append(
            f"descriptor nominalSpatialResolution `{desc['nominalSpatialResolution']}` (~{res_m} m) vs summaries.gsd {gsd}"
        )

    if desc.get("thumbnailLink"):
        log.notes.append(f"descriptor thumbnailLink (not added, hosted thumbnail exists): {desc['thumbnailLink']}")
    if desc.get("eodataPath"):
        log.notes.append(f"descriptor eodataPath (informational): `{desc['eodataPath']}`")


def merge_layer(coll, asset_key, layer, order, log, band=None):
    """Add the fields of a descriptor layer.

    COG: to the item asset `asset_key`. NetCDF: to `band`, the band of the
    Product asset whose name is `asset_key`.
    """
    if band is None:
        asset = coll["item_assets"][asset_key]
        where = f"item_assets.{asset_key}"
        unit_bands = asset.get("bands", [])
    else:
        asset = band
        where = f"item_assets.Product.bands[{asset_key}]"
        unit_bands = [band]

    add_field(asset, "cdse:layer_browser_name", layer["layerBrowserName"], log, where)
    if layer.get("shortDescription"):
        add_field(asset, "cdse:short_description", layer["shortDescription"], log, where)
    if layer.get("longDescription"):
        add_field(asset, "cdse:long_description", layer["longDescription"], log, where)
    add_field(asset, "clms:display", layer["display"], log, where)
    add_field(asset, "clms:display_order", order, log, where)

    unit = layer.get("units", "").strip()
    if unit:
        unit = unit[1:-1] if unit.startswith("[") and unit.endswith("]") else unit
        for unit_band in unit_bands:
            unit_where = where if band is not None else f"{where}.bands[{unit_band.get('name', '?')}]"
            add_field(unit_band, "unit", unit, log, unit_where)

    needs_raster_ext = False
    for desc_key, stac_key in (("scale", "raster:scale"), ("offSet", "raster:offset")):
        number = to_number(layer.get(desc_key, ""))
        if number is None:
            continue
        if stac_key not in asset:
            needs_raster_ext = True
        add_field(asset, stac_key, number, log, where)

    if needs_raster_ext and RASTER_EXT not in coll.get("stac_extensions", []):
        coll.setdefault("stac_extensions", []).append(RASTER_EXT)
        log.added.append("`stac_extensions` + raster/v2.0.0")

    for desc_key, kind, roles in (
        ("colourMapLink", "colormap", ["metadata", "colormap"]),
        ("legendLink", "legend", ["legend"]),
    ):
        href = layer.get(desc_key, "").strip()
        if not href:
            continue
        new_key = f"{asset_key}_{kind}"
        if new_key in coll.get("assets", {}):
            continue
        suffix = Path(href.split("?")[0]).suffix.lower()
        coll.setdefault("assets", {})[new_key] = {
            "href": href,
            "type": MEDIA_TYPES.get(suffix, "application/octet-stream"),
            "title": f"{layer['layerBrowserName']} {kind.replace('colormap', 'colour map')}",
            "roles": roles,
        }
        log.added.append(f"`assets.{new_key}`")


def merge(coll_src, desc, log):
    coll = copy.deepcopy(coll_src)
    merge_collection_level(coll, desc, log)

    netcdf = log.format == "nc"
    if netcdf:
        # the layers are the bands (variables) of the single Product asset
        bands = {b["name"]: b for b in coll["item_assets"]["Product"].get("bands", [])}
        targets, kind = bands, "band"
    else:
        targets = {k: v for k, v in coll.get("item_assets", {}).items() if k != "Product"}
        kind = "item_asset"

    used = {}
    for order, layer in enumerate(desc.get("layers", [])):
        if netcdf:
            keys = match_layer_to_band(layer["fileName"], list(targets.values()))
        else:
            keys = match_layer_to_asset(layer["fileName"], targets)
        if not keys:
            log.unmatched_layers.append(layer["fileName"])
            continue
        if len(keys) > 1:
            log.notes.append(
                f"layer `{layer['fileName']}` maps to {len(keys)} {kind}s: {', '.join(f'`{k}`' for k in keys)}"
            )
        for key in keys:
            if key in used:
                log.conflicts.append(
                    f"layers `{used[key]}` and `{layer['fileName']}` both match {kind} `{key}` (second skipped)"
                )
                continue
            used[key] = layer["fileName"]
            merge_layer(coll, key, layer, order, log, band=targets[key] if netcdf else None)

    log.matched = dict(used)
    log.assets_without_layer = sorted(set(targets) - set(used))
    return coll


def write_report(matched_logs, colls_without_desc, descs_without_coll, source):
    from_cog = [log.name for log in matched_logs if log.format == "cog"]
    lines = [
        "# Data descriptor -> STAC collection merge report",
        "",
        "Generated by `descriptor_to_stac.py`. Merge policy: add-only — existing STAC",
        "values are never modified; conflicting descriptor values are listed here.",
        "",
        f"Collections read from: {source}",
        "",
        "## Coverage",
        "",
        f"- Matched and merged: **{len(matched_logs)}** collections",
        f"  - from the NetCDF collection: {len(matched_logs) - len(from_cog)}",
        f"  - from the COG collection (the catalogue has no NetCDF collection): {len(from_cog)}",
        f"- Datasets in the catalogue without a data descriptor (untouched): {len(colls_without_desc)}",
        f"- Descriptors without a STAC collection (no output): {len(descs_without_coll)}",
        f"- Descriptor layers matched: {sum(len(log.matched) for log in matched_logs)} "
        f"bands/item assets; not matched: {sum(len(log.unmatched_layers) for log in matched_logs)} layers",
        "",
        "### Datasets described from the COG collection",
        "",
        *[f"- `{n}`" for n in from_cog],
        "",
        "### Datasets in the catalogue without a descriptor",
        "",
        *[f"- `{n}`" for n in colls_without_desc],
        "",
        "### Descriptors without a collection",
        "",
        *[f"- `{n}`" for n in descs_without_coll],
        "",
        "Possible near-miss name pairs to review: `lcm` vs `lcfm-lcm`,",
        "`tcd_pantropical` vs `lcfm-tcd_pantropical`, `lie_europe` vs `lie_ceurope`.",
        "",
        "## Known caveats",
        "",
        "- `colourMapLink`/`legendLink` URLs are carried over from the descriptors as-is.",
        "- Only collections are touched here; no items are stored.",
        "- The descriptor layer names follow the COG file names. For a NetCDF collection",
        "  they are matched to the variable names; the pairs are listed per collection",
        "  below so that they can be checked.",
        "- `raster:scale`/`raster:offset` come from the descriptor. They are written to",
        "  the NetCDF bands on the understanding that the COG is produced from the",
        "  NetCDF with the same packing.",
        "",
        "## Per-collection details",
        "",
    ]
    for log in matched_logs:
        target = "NetCDF variable" if log.format == "nc" else "item asset"
        lines.append(f"### {log.name}")
        lines.append("")
        lines.append(f"- Source: `clms_{log.name}_{log.format}`")
        lines.append(f"- Added: {len(log.added)} fields/assets")
        if log.matched:
            pairs = ", ".join(f"`{layer}` → `{key}`" for key, layer in log.matched.items())
            lines.append(f"- Descriptor layer → {target}: {pairs}")
        if log.unmatched_layers:
            lines.append(
                f"- **Unmatched descriptor layers** (no {target} found): "
                f"{', '.join(f'`{n}`' for n in log.unmatched_layers)}"
            )
        if log.assets_without_layer:
            lines.append(
                f"- {target}s without a descriptor layer: "
                f"{', '.join(f'`{n}`' for n in log.assets_without_layer)}"
            )
        for conflict in log.conflicts:
            lines.append(f"- **Conflict**: {conflict}")
        for note in log.notes:
            lines.append(f"- Note: {note}")
        lines.append("")
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def split_id(collection_id):
    """'clms_<name>_nc' -> ('<name>', 'nc'); None for any other id."""
    for fmt in FORMATS:
        if collection_id.startswith("clms_") and collection_id.endswith(f"_{fmt}"):
            return collection_id[len("clms_"):-len(fmt) - 1], fmt
    return None


def fetch_collections():
    """Download the CLMS NetCDF and COG collections from the live CDSE STAC catalogue."""
    request = urllib.request.Request(
        f"{CATALOGUE_URL}/collections?limit=1000", headers={"User-Agent": "descriptor_to_stac"}
    )
    with urllib.request.urlopen(request, timeout=300) as response:
        page = json.load(response)
    if any(link.get("rel") == "next" for link in page.get("links", [])):
        sys.exit("the catalogue returned the collections in several pages; paging is not handled")
    return {c["id"]: c for c in page["collections"] if split_id(c["id"])}


def read_collections(folder):
    collections = {}
    for path in sorted(folder.glob("collection-*.json")):
        with open(path, encoding="utf-8") as f:
            coll = json.load(f)
        if split_id(coll["id"]):
            collections[coll["id"]] = coll
    return collections


def order_like(value, template):
    """Order dict keys like the template; keys the template lacks keep their order after them."""
    if isinstance(value, dict):
        template = template if isinstance(template, dict) else {}
        keys = [k for k in template if k in value] + [k for k in value if k not in template]
        return {k: order_like(value[k], template.get(k)) for k in keys}
    if isinstance(value, list):
        item = template[0] if isinstance(template, list) and template else None
        return [order_like(v, item) for v in value]
    return value


def order_collection(coll, template):
    """Template key order; Product first, then COG layers in Browser display order.

    Lists (the bands of a NetCDF Product among them) keep the catalogue order.
    """
    layer_template = template["item_assets"].get("<item_asset_key>")
    layers = {k: v for k, v in coll["item_assets"].items() if k != "Product"}
    layer_keys = sorted(
        layers, key=lambda k: (layers[k].get("clms:display_order", len(layers)), k.lower())
    )
    item_assets = {}
    if "Product" in coll["item_assets"]:
        item_assets["Product"] = order_like(
            coll["item_assets"]["Product"], template["item_assets"]["Product"]
        )
    for key in layer_keys:
        item_assets[key] = order_like(layers[key], layer_template)

    assets = {}
    for key, asset in coll.get("assets", {}).items():
        assets[key] = order_like(asset, template["assets"]["thumbnail"])

    ordered = order_like(
        {k: v for k, v in coll.items() if k not in ("item_assets", "assets")}, template
    )
    ordered["item_assets"] = item_assets
    ordered["assets"] = assets
    return {k: ordered[k] for k in [k for k in template if k in ordered] + [k for k in ordered if k not in template]}


def main():
    if len(sys.argv) > 2:
        sys.exit(__doc__)
    if len(sys.argv) == 2:
        folder = Path(sys.argv[1])
        if not folder.is_dir():
            sys.exit(f"collections folder not found: {folder}")
        collections = read_collections(folder)
        source = f"folder `{folder}`"
    else:
        collections = fetch_collections()
        source = f"{CATALOGUE_URL} on {datetime.date.today().isoformat()}"

    templates = {}
    for fmt, path in TEMPLATE_PATHS.items():
        with open(path, encoding="utf-8") as f:
            templates[fmt] = json.load(f)

    # dataset name -> formats the catalogue serves it in
    served = {}
    for cid in collections:
        name, fmt = split_id(cid)
        served.setdefault(name, set()).add(fmt)
    desc_names = {
        d.name for d in DATASETS_DIR.iterdir() if (d / "data_descriptor" / f"{d.name}.json").is_file()
    }

    matched = sorted(set(served) & desc_names)
    colls_without_desc = sorted(set(served) - desc_names)
    descs_without_coll = sorted(desc_names - set(served))

    logs = []
    for name in matched:
        # NetCDF is the reference; COG only when it is all the catalogue serves
        fmt = next(f for f in FORMATS if f in served[name])
        cid = f"clms_{name}_{fmt}"
        coll_src = collections[cid]
        coll_src["links"] = [l for l in coll_src.get("links", []) if l.get("rel") not in API_LINK_RELS]
        with open(DATASETS_DIR / name / "data_descriptor" / f"{name}.json", encoding="utf-8") as f:
            desc = json.load(f)

        log = CollectionLog(name, fmt)
        merged = order_collection(merge(coll_src, desc, log), templates[fmt])
        logs.append(log)

        out_dir = DATASETS_DIR / name / "stac" / "collection"
        out_dir.mkdir(parents=True, exist_ok=True)
        out_path = out_dir / f"collection-{cid}.json"
        with open(out_path, "w", encoding="utf-8", newline="\n") as f:
            json.dump(merged, f, indent=2, ensure_ascii=False)
            f.write("\n")

        # one collection per dataset: drop the placeholder and the collection of the other format
        stale = [out_dir / ".gitkeep"] + [
            out_dir / f"collection-clms_{name}_{other}.json" for other in FORMATS if other != fmt
        ]
        for path in stale:
            if path.is_file():
                path.unlink()

    write_report(logs, colls_without_desc, descs_without_coll, source)

    total_added = sum(len(l.added) for l in logs)
    total_conflicts = sum(len(l.conflicts) for l in logs)
    total_unmatched = sum(len(l.unmatched_layers) for l in logs)
    print(f"merged {len(logs)} collections "
          f"({sum(l.format == 'nc' for l in logs)} NetCDF, {sum(l.format == 'cog' for l in logs)} COG), "
          f"{total_added} additions, {total_conflicts} conflicts, {total_unmatched} unmatched layers")
    print(f"report: {REPORT_PATH}")


if __name__ == "__main__":
    main()
